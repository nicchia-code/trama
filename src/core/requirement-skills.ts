import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { stringify } from "yaml";
import { type Area, type Fragment, hasContent, loadProject, REQUIREMENT_SKILLS_BUDGET, type RequirementSection } from "./requirements";
import { type Project, writeFileEnsuringDir } from "./store";

/** Folders, relative to the project root, where agents look for skills and Trama may have installed its own. */
export const SKILL_DIRS = [".agents/skills", ".claude/skills", ".github/skills"];

const PREFIX = "trama-req-";

/** One skill per fragment while the fragments' names and descriptions fit the budget; one index skill per Area beyond it. */
export type RequirementSkillMode = "fragment" | "index";

/** Written in every index skill, so a later regeneration can tell which mode the skills on disk were generated in. */
const INDEX_MARK = "This is the index of the Area's Requirements.";

const FOLLOW = [
  "These are the developer's Requirements for how the System is built. Follow them when you write code. The Model (`.trama/model/`) says what the System does; when a Requirement and the Model disagree, stop and tell the developer.",
  "A section titled with a Model reference (such as `order/Paid`) applies to that element and to everything inside it.",
];

/** The skill folders of this project that hold Trama's skills (those with `trama-design`): the usual ones plus `extra` (relative to the root or absolute). */
export function tramaSkillDirs(root: string, extra: string[] = []): string[] {
  const dirs = [...new Set([...SKILL_DIRS, ...extra].map((d) => resolve(root, d)))];
  return dirs.filter((d) => existsSync(join(d, "trama-design", "SKILL.md")));
}

const filled = (sections: RequirementSection[]) => sections.filter((s) => s.text !== "");

/** The skill name of a fragment in fragment mode. */
export const fragmentSkillName = (area: Area, fragment: Fragment) => `${PREFIX}${area.id}-${fragment.id}`;

/** The skill name of an Area in index mode. */
export const indexSkillName = (area: Area) => `${PREFIX}${area.id}`;

/** Fragments that have something for an agent to read. */
export const fragmentsWithContent = (area: Area) => area.fragments.filter((f) => filled(f.sections).length > 0);

/** Characters the fragment skills would take in the agents' skill list: each name plus its description. */
export function requirementSkillsBudget(areas: Area[]): number {
  let used = 0;
  for (const area of areas) for (const f of fragmentsWithContent(area)) used += fragmentSkillName(area, f).length + f.description.length;
  return used;
}

/** The mode the Requirement skills of these Areas are generated in, and the budget they use. */
export function requirementSkillMode(areas: Area[]): { mode: RequirementSkillMode; budget: number } {
  const budget = requirementSkillsBudget(areas);
  return { mode: budget <= REQUIREMENT_SKILLS_BUDGET ? "fragment" : "index", budget };
}

/**
 * The Requirement skills that hold `section` of `area`, or the whole Area when `section` is null, as the current
 * mode of `areas` generates them: fragment skills in fragment mode, the Area's index skill in index mode. Empty when
 * nothing of it is generated (an empty section, or an Area with nothing to read).
 */
export function requirementSkillNames(areas: Area[], area: Area, section: RequirementSection | null = null): string[] {
  if (section !== null && section.text === "") return [];
  if (requirementSkillMode(areas).mode === "index") return hasContent(area) ? [indexSkillName(area)] : [];
  return fragmentsWithContent(area)
    .filter((f) => section === null || f.file === section.file)
    .map((f) => fragmentSkillName(area, f));
}

const sectionBlocks = (sections: RequirementSection[]) => filled(sections).flatMap((s) => ["", `## ${s.ref ?? "General"}`, "", s.text]);

const skillFile = (name: string, description: string, body: string[]) =>
  `---\n${stringify({ name, description }, { lineWidth: 0 }).trimEnd()}\n---\n${[...body, ""].join("\n").replace(/\n{3,}/g, "\n\n")}`;

/** The generated `SKILL.md` of a fragment, in fragment mode. */
export function renderFragmentSkill(area: Area, fragment: Fragment): string {
  return skillFile(fragmentSkillName(area, fragment), fragment.description, [
    `# Requirements: ${area.title}, ${fragment.title}`,
    "",
    `Generated by Trama from \`.trama/${fragment.file}\`. Do not edit this file: change the Requirements through a Trama Proposal (or ask the developer).`,
    "",
    ...FOLLOW,
    area.intro ? `\n${area.intro}` : "",
    ...sectionBlocks(fragment.sections),
  ]);
}

/** The files of an Area's index skill, by name in the skill folder: `SKILL.md` and one `<fragment>.md` per fragment with content. */
export function renderIndexSkill(area: Area): Map<string, string> {
  const fragments = fragmentsWithContent(area);
  const general = area.sections.find((s) => s.ref === null && s.text !== "");
  const files = new Map<string, string>();
  files.set(
    "SKILL.md",
    skillFile(indexSkillName(area), area.description, [
      `# Requirements: ${area.title}`,
      "",
      `Generated by Trama from \`.trama/${area.file.replace(/area\.md$/, "")}\`. Do not edit these files: change the Requirements through a Trama Proposal (or ask the developer).`,
      "",
      ...FOLLOW,
      `${INDEX_MARK} The General Requirements are below in full; every other section is in the file of its fragment, next to this one: read the fragments whose sections name the elements you work on.`,
      area.intro ? `\n${area.intro}` : "",
      ...(general ? ["", "## General", "", general.text] : []),
      ...(fragments.length > 0 ? ["", "## Fragments", ""] : []),
      ...fragments.map((f) => {
        const refs = filled(f.sections).map((s) => `\`${s.ref ?? "General"}\``);
        return `- **${f.title}** (\`${f.id}.md\`): ${f.description} Sections: ${refs.join(", ")}.`;
      }),
    ]),
  );
  for (const f of fragments) {
    const rest = f.sections.filter((s) => s.ref !== null);
    files.set(
      `${f.id}.md`,
      [`# Requirements: ${area.title}, ${f.title}`, "", f.description, ...(filled(rest).length > 0 ? sectionBlocks(rest) : ["", "Its General section is in SKILL.md."]), ""]
        .join("\n")
        .replace(/\n{3,}/g, "\n\n"),
    );
  }
  return files;
}

/** The files the Requirement skills consist of in `mode`, keyed by `<skill>/<file>`. */
function wantedFiles(areas: Area[], mode: RequirementSkillMode): Map<string, string> {
  const wanted = new Map<string, string>();
  for (const area of areas) {
    if (mode === "fragment") for (const f of fragmentsWithContent(area)) wanted.set(`${fragmentSkillName(area, f)}/SKILL.md`, renderFragmentSkill(area, f));
    else if (hasContent(area)) for (const [name, content] of renderIndexSkill(area)) wanted.set(`${indexSkillName(area)}/${name}`, content);
  }
  return wanted;
}

/** The mode of the generated skills already in these folders, or null when there are none. */
function modeOnDisk(dirs: string[]): RequirementSkillMode | null {
  let found: RequirementSkillMode | null = null;
  for (const dir of dirs)
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || !entry.name.startsWith(PREFIX)) continue;
      const file = join(dir, entry.name, "SKILL.md");
      if (existsSync(file) && readFileSync(file, "utf8").includes(INDEX_MARK)) return "index";
      found = "fragment";
    }
  return found;
}

export interface RequirementSkillSync {
  mode: RequirementSkillMode;
  /** Characters the fragment skills take, out of `REQUIREMENT_SKILLS_BUDGET`. */
  budget: number;
  /** The mode the skills on disk were in when it differs from `mode`; null when nothing switched. */
  switchedFrom: RequirementSkillMode | null;
  /** Files written and skill folders or files removed. */
  changed: string[];
}

/**
 * Brings the generated `trama-req-*` skills in line with the project's Requirements, in every skill folder where
 * Trama's skills are installed: writes the files whose content changes and removes every `trama-req-*` skill, or
 * file inside one, that the current mode does not produce.
 */
export function syncRequirementSkills(p: Project, extraDirs: string[] = []): RequirementSkillSync {
  const areas = loadProject(p).areas;
  const { mode, budget } = requirementSkillMode(areas);
  const dirs = tramaSkillDirs(p.root, extraDirs);
  const before = modeOnDisk(dirs);
  const wanted = wantedFiles(areas, mode);
  const skills = new Set([...wanted.keys()].map((k) => k.split("/")[0] as string));
  const changed: string[] = [];
  for (const dir of dirs) {
    for (const [rel, content] of wanted) {
      const file = join(dir, rel);
      if (existsSync(file) && readFileSync(file, "utf8") === content) continue;
      writeFileEnsuringDir(file, content);
      changed.push(file);
    }
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || !entry.name.startsWith(PREFIX)) continue;
      const folder = join(dir, entry.name);
      if (!skills.has(entry.name)) {
        rmSync(folder, { recursive: true, force: true });
        changed.push(folder);
        continue;
      }
      for (const file of readdirSync(folder))
        if (!wanted.has(`${entry.name}/${file}`)) {
          rmSync(join(folder, file), { recursive: true, force: true });
          changed.push(join(folder, file));
        }
    }
  }
  return { mode, budget, switchedFrom: before !== null && before !== mode ? before : null, changed };
}

/** The lines that report a regeneration: the mode, the budget used and, when it happened, the switch. */
export function describeRequirementSkillSync(sync: RequirementSkillSync): string {
  const modeName = (m: RequirementSkillMode) => (m === "fragment" ? "one skill per fragment" : "one index skill per Area");
  const lines = [`Requirement skills: ${modeName(sync.mode)} (budget ${sync.budget}/${REQUIREMENT_SKILLS_BUDGET} characters).`];
  if (sync.switchedFrom) lines.push(`Switched from ${modeName(sync.switchedFrom)} to ${modeName(sync.mode)}.`);
  if (sync.changed.length > 0) lines.push(`Regenerated ${sync.changed.length} Requirement skill file(s):\n${sync.changed.map((c) => `- ${c}`).join("\n")}`);
  return lines.join("\n");
}
