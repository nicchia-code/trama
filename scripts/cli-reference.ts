// Writes the command reference of docs/cli.md from the command registry: `bun run docs:cli`.
// The reference sits between two markers; test/cli-reference.test.ts fails while the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { REGISTRY } from "../src/cli/commands";
import { commandReference } from "../src/cli/help";

export const REFERENCE_START = "<!-- commands:start (generated by `bun run docs:cli` from the command registry; do not edit by hand) -->";
export const REFERENCE_END = "<!-- commands:end -->";

/** The generated block, markers included. */
export const referenceBlock = (): string => `${REFERENCE_START}\n\n${commandReference(REGISTRY)}\n\n${REFERENCE_END}`;

/** The document with the block between the markers replaced. */
export function withReference(doc: string): string {
  const start = doc.indexOf(REFERENCE_START);
  const end = doc.indexOf(REFERENCE_END);
  if (start < 0 || end < start) throw new Error(`docs/cli.md needs the markers ${REFERENCE_START} and ${REFERENCE_END}`);
  return `${doc.slice(0, start)}${referenceBlock()}${doc.slice(end + REFERENCE_END.length)}`;
}

if (import.meta.main) {
  const path = "docs/cli.md";
  writeFileSync(path, withReference(readFileSync(path, "utf8")));
}
