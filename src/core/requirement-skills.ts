import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { stringify } from "yaml";
import { type Area, hasContent, loadProject } from "./requirements";
import { type Project, writeFileEnsuringDir } from "./store";

/** Folders, relative to the project root, where agents look for skills and Trama may have installed its own. */
export const SKILL_DIRS = [".agents/skills", ".claude/skills", ".github/skills"];

const PREFIX = "trama-req-";

/** The skill folders of this project that hold Trama's skills (those with `trama-design`): the usual ones plus `extra` (relative to the root or absolute). */
export function tramaSkillDirs(root: string, extra: string[] = []): string[] {
  const dirs = [...new Set([...SKILL_DIRS, ...extra].map((d) => resolve(root, d)))];
  return dirs.filter((d) => existsSync(join(d, "trama-design", "SKILL.md")));
}

/** The generated `SKILL.md` for an Area. */
export function renderAreaSkill(area: Area): string {
  const front = stringify({ name: `${PREFIX}${area.id}`, description: area.description }, { lineWidth: 0 }).trimEnd();
  const body = [
    `# Requirements: ${area.title}`,
    "",
    `Generated by Trama from \`.trama/${area.file}\`. Do not edit this file: change the Requirements through a Trama Proposal (or ask the developer).`,
    "",
    "These are the developer's Requirements for how the System is built. Follow them when you write code. The Model (`.trama/model/`) says what the System does; when a Requirement and the Model disagree, stop and tell the developer.",
    "A section titled with a Model reference (such as `order/Paid`) applies to that element and to everything inside it.",
    area.intro ? `\n${area.intro}` : "",
    ...area.sections.filter((s) => s.text !== "").flatMap((s) => ["", `## ${s.ref ?? "General"}`, "", s.text]),
    "",
  ];
  return `---\n${front}\n---\n${body.join("\n").replace(/\n{3,}/g, "\n\n")}`;
}

/**
 * Brings the generated `trama-req-<area>` skills in line with the project's Requirements, in every skill folder
 * where Trama's skills are installed: writes changed ones, removes those of deleted or empty Areas.
 * Returns the files written or removed.
 */
export function syncRequirementSkills(p: Project, extraDirs: string[] = []): string[] {
  const areas = loadProject(p).areas.filter(hasContent);
  const changed: string[] = [];
  for (const dir of tramaSkillDirs(p.root, extraDirs)) {
    const wanted = new Map(areas.map((a) => [`${PREFIX}${a.id}`, renderAreaSkill(a)]));
    for (const [name, content] of wanted) {
      const file = join(dir, name, "SKILL.md");
      if (existsSync(file) && readFileSync(file, "utf8") === content) continue;
      writeFileEnsuringDir(file, content);
      changed.push(file);
    }
    for (const entry of readdirSync(dir, { withFileTypes: true }))
      if (entry.isDirectory() && entry.name.startsWith(PREFIX) && !wanted.has(entry.name)) {
        rmSync(join(dir, entry.name), { recursive: true, force: true });
        changed.push(join(dir, entry.name));
      }
  }
  return changed;
}
